import math
import random

# This code produces a matrix A, a cost vector c, and a capacity vector u for a circulation LP of
# the form max c^Tx subject to Ax=0, 0 \leq x \leq u.  The cost vector c should have all positive entries, but not all equal to avoid all circuits having the same normalized cost.
# This instance is constructed by generating cycles and adding some uniform capacity to all arcs in the generated cycle.  
# This, with the chosen cost vector, ensures that the optimal solution has cost equal to the sum of the capacities.

def circulation(n=500, num_cycles=750, max_capacity=50):
    # n = 500 # n is the number of vertices
    f = math.comb(n,2) # f is the number of edges in the complete undirected graph on n vertices.
    m = 2*f # m is the number of arcs in the complete bidirected graph on n vertices.
    A = [[0 for col in range(m)] for row in range(n)] # A[i] is a row of A, A[i][j] is the index in row i column j
    # A is initialized to have the dimensions of a complete directed graph (all possible arcs, including both directions), but all entries 0.  Only when an arc is actually
    # added to the graph are the appropriate entries of A replaced with 1's and -1's.  
    # There is a deterministic way in which column entries are associated to pairs of vertices (rows), explained below.
    
    u = [0 for i in range(m)] # u is the vector of capacities on each arc
    max_cost = m**2 # this is the maximum entry allowed in the cost vector.  I have no idea how large this should be relative to m or n.
    c = [random.randrange(1,max_cost+1) for i in range(m)] # c is the cost vector.  It is generated by populating each entry with a random integer between 1 and max_cost
    # num_cycles = 750 # the number of cycles we are going to add to our graph.  I truly have no idea how large this should be relative to n.
    max_cycle_len = n # this is the maximum number of vertices that should appear in a cycle we generate.  It is set to n by default, but it may be reasonable to lower it.
    # max_capacity = 50 # this is the maximum capacity that a cycle we add should have.  I truly have no idea how large this should be relative to n.
    
    # The vertices of G are the numbers 0, ... , n-1, the same as the row indices of A.
    # The column indices 0, ... , f-1, f, 2f-1 of of A (corresponding to edges) are assumed to correspond to arcs in the following way:
    
    # The first f-1 columns all correspond to arcs going from a smaller index to a larger index.
    # Column 0 corresponds to the arc (0,1), column 1 to the arc (0,2), ... , 
    # column (n-2) to the arc (0,n-1), column n-1 to the arc (1,2), column n to the arc (1,3), and so on like this. 
    # For column indices j greater than or equal to f, column j corresponds to the reverse of the arc indexed by j-f.  
    # For example, column f+1 corresponds to the arc (2,0). 
    
    # It is necessary to be able to go back and forth between column indices and the pair of vertices (rows v1 and v2) that
    # the column corresponds to.  In particular, when an edge is added to the graph, we need to know which entries of
    # A to set to 1 and -1, which requires knowing the appropriate row numbers (which are exactly v1 and v2)
    
    # The next two functions do this.  
    # The function get_Edge takes a column index and returns the vertices the corresponding edge is incident to.  
    # The function get_Edge_Index takes two vertices v1 and v2 and returns the column index corresponding to the arc (v1, v2)
    
    def get_Edge(column):
        reverse = column>=f
        col=column
        if(reverse):
            col = column-f
        subtract = n
        idx = col
        while (idx>=0):
            subtract-=1
            idx = idx - subtract
        idx = idx + subtract
        v1 = n - (subtract+1)
        v2 = v1 + 1 + idx
        if(reverse):
            return [v2,v1]
        return [v1,v2]
    
    def get_Edge_Index(v1,v2):
        reverse = v1>v2
        u1=v1
        u2=v2
        if reverse:
            u1=v2
            u2=v1
        idx = 0
        add = n - 1
        loops = u1
        while(loops>0):
            idx = idx + add
            add-=1
            loops-=1
        idx = idx + (u2 - u1 - 1)
        if reverse:
            return idx+f
        return idx
    
    # The following function gen_Cycle takes as input an integer 'length' and returns a list of size 'length' of vertices
    # (i.e. integers between 0 and n-1) to comprise a directed cycle (in the order in which they appear in the cycle) 
    def gen_Cycle(length):
        verts = [i for i in range(n)]
        random.shuffle(verts)
        cycle = [verts[i] for i in range(length)]   
        return cycle
    
    # The following function add_Cycle takes as input a list 'cycle' of vertices (i.e. integers between 0 and n-1) and an
    # integer 'capacity.' It "adds" the appropriate arcs by setting the appropriate entries of A to be 1 and -1 and it adds
    # 'capacity' to the appropriate entries of the capacity vector.
    def add_Cycle(cycle, capacity):
        length = len(cycle)
        for i in range(length):
            v1 = cycle[i]
            v2 = cycle[(i+1)%length]
            edge_idx = get_Edge_Index(v1,v2)
            A[v1][edge_idx]=-1
            A[v2][edge_idx]=1
            u[edge_idx]=u[edge_idx]+capacity
    
    def gen_Instance():
        for i in range(num_cycles):
            cycle=gen_Cycle(random.randrange(3,max_cycle_len+1))#generates a cycle whose length is a random number between 3 and max_cycle_len
            capacity = random.randrange(1,max_capacity+1)
            add_Cycle(cycle,capacity)
        # At this point, A and u are what we want them to be.

    # This functions finds the indices of the all-zero columns in A and deletes them. An all-zero column corresponds to an arc that is not
    # contained within our network, so we can safely remove such columns without affecting the solutions of our LP.
    def remove_All_Zero_Columns():
        all_zero_column_indices = []
        for j in range(m):
            column_A = [A[i][j] for i in range(n)]
            if column_A == [0 for i in range(n)]:
                all_zero_column_indices.append(j)
        all_zero_column_indices.reverse()
        for j in all_zero_column_indices:
            for row in A:
                row.pop(j)
            c.pop(j)
            u.pop(j)
        

    gen_Instance()
    remove_All_Zero_Columns()
    
    return A, u, c


# In the end, there may be arcs which were never added to the graph because they never appeared in any cycle.  The
# corresponding columns of A and entries of u will all be 0, and there may be value in cleaning this up after the fact.
# On the other hand, removing these columns might be something Gurobi does on its own immediately.


# get_Edges recovers the (tail, head) pair of every column of A: the tail is the row with -1 and the head is the row with +1.
# This is needed because circulation() returns only A, u and c, and the columns no longer line up with a fixed arc
# numbering once the all-zero columns have been removed.
def get_Edges(A):
    n = len(A)
    m = len(A[0]) if n > 0 else 0
    tails = [None] * m
    heads = [None] * m
    for i in range(n):
        row = A[i]
        for j in range(m):
            if row[j] == -1:
                tails[j] = i
            elif row[j] == 1:
                heads[j] = i
    return list(zip(tails, heads))


# write_mps writes the LP  max c^Tx  s.t.  Ax = 0,  0 <= x <= u  to an MPS file.
# Rows are named v0, v1, ... (one per vertex) and column j is named x_{tail}_{head} using edges[j].
def write_mps(filename, name, A, u, c, edges):
    n = len(A)
    with open(filename, "w") as f:
        f.write(f"NAME          {name}\n")
        f.write("OBJSENSE\n    MAX\n")
        f.write("ROWS\n")
        f.write(" N  obj\n")
        for i in range(n):
            f.write(f" E  v{i}\n")
        f.write("COLUMNS\n")
        for j, (v1, v2) in enumerate(edges):
            col = f"x_{v1}_{v2}"
            f.write(f"    {col}  obj  {c[j]}\n")
            f.write(f"    {col}  v{v1}  {A[v1][j]}\n")
            f.write(f"    {col}  v{v2}  {A[v2][j]}\n")
        f.write("RHS\n")  # all right-hand sides are 0, which is the MPS default, so nothing to list
        f.write("BOUNDS\n")
        for j, (v1, v2) in enumerate(edges):
            f.write(f" UP BND  x_{v1}_{v2}  {u[j]}\n")
        f.write("ENDATA\n")


# Running this file creates num_per_n instances for each n in n_values, written as MPS files into out_dir.
# It also writes summary.csv listing each instance with its size and its known optimal value.
# Since every cost is positive and x = u is feasible (it is a sum of cycle flows), x = u is optimal, so the
# optimal value is c^T u (not sum(u), because c is not the all-ones vector here).
# Each instance uses its own seed, so rerunning reproduces exactly the same files.
if __name__ == "__main__":
    import os

    n_values = [50, 100, 150, 200, 250]
    num_per_n = 10
    out_dir = "cycle_instances"

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "summary.csv"), "w") as summary:
        summary.write("file,n,m,seed,optimal_value\n")
        for n in n_values:
            for k in range(1, num_per_n + 1):
                seed = n * 1000 + k
                random.seed(seed)
                A, u, c = circulation(n=n)
                edges = get_Edges(A)
                opt = sum(c[j] * u[j] for j in range(len(u)))
                name = f"circ_n{n}_{k:02d}"
                write_mps(os.path.join(out_dir, name + ".mps"), name, A, u, c, edges)
                summary.write(f"{name}.mps,{n},{len(edges)},{seed},{opt}\n")
                print(f"{name}: n={n}, m={len(edges)}, optimal value={opt}")